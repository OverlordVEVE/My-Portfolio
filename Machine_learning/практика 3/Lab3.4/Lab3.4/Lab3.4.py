import pandas as pd
import os
import csv

# -------------------------------------------------------------------
# 1. Путь к папке с файлами
# -------------------------------------------------------------------
FOLDER_PATH = r"C:\123\машинное обучение\практика 3\Lab3.4"

# -------------------------------------------------------------------
# 2. Чтение исходного файла
# -------------------------------------------------------------------
input_file = os.path.join(FOLDER_PATH, "Japan_stat_1950.xlsx")

df = pd.read_excel(
    input_file,
    sheet_name="Japan-1950",
    skiprows=5,        # пропускаем 5 пустых строк (данные с 6-й)
    usecols="C:E",     # берём столбцы C, D, E
    header=0           # строка 6 содержит заголовки Age, M, F
)

# -------------------------------------------------------------------
# 3. Расчёты
# -------------------------------------------------------------------
df['Total'] = df['M'] + df['F']
df['Male_share'] = df['M'] / df['Total']
df['Female_share'] = 1 - df['Male_share']

# -------------------------------------------------------------------
# 4. Сохранение CSV для корректного открытия в Excel (русская версия)
# -------------------------------------------------------------------
csv_output = os.path.join(FOLDER_PATH, "Japan_stat_1950_result.csv")

df.to_csv(
    csv_output,
    index=False,
    sep=';',                    
    encoding='utf-8-sig',        
    quoting=csv.QUOTE_NONNUMERIC,
    float_format='%.8f'          
)

# -------------------------------------------------------------------
# 5. Сохранение Excel-версии (по заданию)
# -------------------------------------------------------------------
xlsx_output = os.path.join(FOLDER_PATH, "Japan_stat_1950_result.xlsx")
df.to_excel(xlsx_output, index=False)

# -------------------------------------------------------------------
# 6. Вывод информации и инструкция
# -------------------------------------------------------------------
print("✅ Обработка завершена. Файлы сохранены:")
print(f"📁 CSV  : {csv_output}")
print(f"📁 Excel: {xlsx_output}")