import numpy as np

# Настройка формата вывода
np.set_printoptions(precision=2, suppress=True)  # Изменил на 2 знака после запятой

print("=" * 60)
print("СОЗДАНИЕ МАССИВОВ NUMPY")
print("=" * 60)

# a) Создание одномерного массива с пятью элементами вещественного типа
a = np.array([1.5, 2.7, 3.2, 4.8, 5.1], dtype=float)
print("\na) Одномерный массив с 5 вещественными элементами:")
print(a)
print(f"Форма: {a.shape}, Тип: {a.dtype}")

# b) Создание двумерного массива (3, 4) со случайными целыми [0, 20)
b = np.random.randint(0, 20, size=(3, 4))
print("\nb) Двумерный массив 3x4 со случайными целыми [0, 20):")
print(b)
print(f"Форма: {b.shape}, Тип: {b.dtype}")

# c) Создание трехмерного массива (3, 4, 5) со случайными вещественными [-5, 10)
c = np.random.uniform(-5, 10, size=(3, 4, 5))
print("\nc) Трехмерный массив 3x4x5 со случайными вещественными [-5, 10):")
print("Форма:", c.shape)
print(f"Тип: {c.dtype}")
print("Весь трехмерный массив:")
for i in range(c.shape[0]):
    print(f"\nМатрица {i}:")
    print(c[i])

# d) Повторение строк массива b дважды
d = np.repeat(b, repeats=2, axis=0)
print("\nd) Массив b с повторенными строками (каждая строка 2 раза):")
print(d)
print(f"Форма: {d.shape}")

# e) Повторение столбцов массива b (1-й и 3-й - дважды, 2-й и 4-й - один раз)
e = np.repeat(b, repeats=[2, 1, 2, 1], axis=1)
print("\ne) Массив b с повторенными столбцами:")
print("Повторения: [2, 1, 2, 1] (1-й и 3-й - 2 раза, 2-й и 4-й - 1 раз)")
print(e)
print(f"Форма: {e.shape}")

# f) Создание двумерного массива (4, 3), заполненного нулями целого типа
f = np.zeros((4, 3), dtype=int)
print("\nf) Двумерный массив 4x3, заполненный нулями целого типа:")
print(f)
print(f"Форма: {f.shape}, Тип: {f.dtype}")

# g) Создание трехмерного массива (2, 4, 5), заполненного единицами вещественного типа
g = np.ones((2, 4, 5), dtype=float)
print("\ng) Трехмерный массив 2x4x5, заполненный единицами вещественного типа:")
print("Форма:", g.shape)
print(f"Тип: {g.dtype}")
print("Весь трехмерный массив:")
for i in range(g.shape[0]):
    print(f"\nМатрица {i}:")
    print(g[i])

# h) Создание одномерного массива от 100 до 500 с шагом 20
h = np.arange(100, 501, 20)
print("\nh) Одномерный массив от 100 до 500 с шагом 20:")
print(h)
print(f"Форма: {h.shape}, Тип: {h.dtype}")

# i) Создание одномерного массива из 15 элементов, равномерно распределенных на [50, 300]
# Временно меняем настройки для этого массива, чтобы показать 2 знака
np.set_printoptions(precision=2, suppress=True)
i = np.linspace(50, 300, 15)
print("\ni) Одномерный массив из 15 элементов, равномерно распределенных на [50, 300]:")
print(i)
print(f"Форма: {i.shape}, Тип: {i.dtype}")

# j) Создание двумерного массива (5, 4) со случайными числами [0, 1)
j = np.random.random((5, 4))
print("\nj) Двумерный массив 5x4 со случайными числами [0, 1):")
print(j)
print(f"Форма: {j.shape}, Тип: {j.dtype}")

print("\n" + "=" * 60)
print("ВСЕ МАССИВЫ СОЗДАНЫ УСПЕШНО")
print("=" * 60)

# Дополнительная информация о созданных массивах
print("\n" + "-" * 60)
print("СВОДНАЯ ИНФОРМАЦИЯ О МАССИВАХ:")
print("-" * 60)

# Создаем словарь с массивами
arrays = {
    'a': a, 'b': b, 'c': c, 'd': d, 'e': e,
    'f': f, 'g': g, 'h': h, 'i': i, 'j': j
}

# Правильно выводим информацию о массивах
for name, array in arrays.items():
    if array.dtype in [np.float32, np.float64]:
        min_val = f"{array.min():.2f}"
        max_val = f"{array.max():.2f}"
    else:
        min_val = f"{array.min()}"
        max_val = f"{array.max()}"
    
    print(f"{name}) Форма: {str(array.shape):12s} | Тип: {str(array.dtype):10s} | "
          f"Размер: {array.size:3d} | Минимум: {min_val:>6s} | "
          f"Максимум: {max_val:>6s}")