import numpy as np

# Настраиваем формат вывода для всей сессии
np.set_printoptions(precision=1, suppress=True)

print("=" * 60)
print("ИНДЕКСАЦИЯ И СРЕЗЫ МАССИВОВ")
print("=" * 60)

# a) Создание одномерного массива с помощью linspace (не менее 7 элементов)
a = np.linspace(0, 60, 8)  # 8 элементов от 0 до 60
print("\na) Одномерный массив linspace(0, 60, 8):")
print(a)
print("Первый элемент:", a[0])
print("Третий элемент:", a[2])
print("Последний элемент:", a[-1])

# b) Изменение значений третьего, четвертого и шестого элементов на нулевые значения
a[2] = 0  # третий элемент (индекс 2)
a[3] = 0  # четвертый элемент (индекс 3)
a[5] = 0  # шестой элемент (индекс 5)
print("\nb) Массив после изменения 3-го, 4-го и 6-го элементов на 0:")
print(a)

# c) Создание двумерного массива (4, 5) с помощью rand (случайные числа [0, 1))
b = np.random.rand(4, 5) * 100  # умножаем на 100 для более читаемых значений
print("\nc) Двумерный массив 4x5 (исходный):")
print(b)

# Изменение элемента во второй строке и третьем столбце на 10
b[1, 2] = 10  # вторая строка (индекс 1), третий столбец (индекс 2)
print("\nМассив после изменения элемента [1, 2] на 10:")
print(b)

# d) Изменение значений элементов по углам массива на 0
print("\nd) Изменение угловых элементов на 0:")

b[0, 0] = 0      # верхний левый
b[0, -1] = 0     # верхний правый  
b[-1, 0] = 0     # нижний левый
b[-1, -1] = 0    # нижний правый

print("\nПолучившаяся таблица:")
print(b)

# e) Увеличение значения элемента в третьей строке и третьем столбце на 15
print("\ne) Увеличение элемента [2, 2] на 15:")
print(f"Было: {b[2, 2]:.1f} → Стало: {b[2, 2] + 15:.1f}")
b[2, 2] += 15

print("\nПолучившаяся таблица:")
print(b)

# f) Создание трехмерного массива (3, 4, 3) со случайными целыми [30, 100)
c = np.random.randint(30, 100, size=(3, 4, 3))
print("\nf) Трехмерный массив 3x4x3 со случайными целыми [30, 100):")
print("Форма:", c.shape)

print("\nВсе матрицы:")
for i in range(3):
    print(f"Матрица {i}:")
    print(c[i])
    print()

# Обращение только к элементам второй матрицы
print("Обращение только ко второй матрице (c[1]):")
print(c[1])

# g) Обращение к элементам второй и третьей строк первой матрицы (все столбцы)
print("\ng) Вторая и третья строки первой матрицы (c[0, 1:3, :]):")
print("Индексация c[0, 1:3, :]")
print(c[0, 1:3, :])

# h) Последние строки каждой матрицы во втором и третьем столбцах
print("\nh) Последние строки каждой матрицы (2-й и 3-й столбцы):")
print("Индексация c[:, -1, 1:3]")
print(c[:, -1, 1:3])

# i) Первые три строки каждой матрицы в двух последних столбцах
print("\ni) Первые три строки каждой матрицы в двух последних столбцах:")
print("Индексация c[:, :3, -2:]")
print(c[:, :3, -2:])

print("\n" + "=" * 60)
print("ЗАДАНИЕ ВЫПОЛНЕНО")
print("=" * 60)
