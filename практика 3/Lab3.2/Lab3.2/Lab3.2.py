# Импорт библиотек
import pandas as pd
import numpy as np

# ------------------------------------------------------------
# a) DataFrame из списка вложенных списков + названия столбцов
# ------------------------------------------------------------
# Создаём список, содержащий два вложенных списка (строки будущей таблицы)
list_of_lists = [
    [1, 2, 3],
    [4, 5, 6]
]
# Задаём названия столбцов
column_names = ['col1', 'col2', 'col3']
df_a = pd.DataFrame(list_of_lists, columns=column_names)
print("a) DataFrame из списка вложенных списков:")
print(df_a)
print()

# ------------------------------------------------------------
# b) DataFrame из словаря (ключи -> столбцы, значения -> списки)
# ------------------------------------------------------------
# Ключи — названия столбцов, значения — списки вещественных чисел
data_dict = {
    'A': [1.1, 2.2, 3.3],
    'B': [4.4, 5.5, 6.6],
    'C': [7.7, 8.8, 9.9]
}
df_b = pd.DataFrame(data_dict)
print("b) DataFrame из словаря:")
print(df_b)
print()

# ------------------------------------------------------------
# c) DataFrame из двумерного массива NumPy с собственными индексами строк и столбцов
# ------------------------------------------------------------
# Создаём массив 4x5 (4 строки, 5 столбцов) с целыми числами
np_array = np.random.randint(10, 100, size=(4, 5))
# Задаём индексы строк и названия столбцов
row_index = ['row1', 'row2', 'row3', 'row4']
col_index = ['c1', 'c2', 'c3', 'c4', 'c5']
df_c = pd.DataFrame(np_array, index=row_index, columns=col_index)
print("c) DataFrame из массива NumPy с кастомными индексами:")
print(df_c)
print()

# ------------------------------------------------------------
# d) Атрибуты values и index для DataFrame из пункта c
# ------------------------------------------------------------
print("d) Атрибуты values и index для df_c:")
print("Значения (values):")
print(df_c.values)
print("\nИндексы строк (index):")
print(df_c.index)
print()

# ------------------------------------------------------------
# e) Названия столбцов DataFrame из пункта c (атрибут columns)
# ------------------------------------------------------------
print("e) Названия столбцов df_c:")
print(df_c.columns)
print()

# ------------------------------------------------------------
# f) Обращение к ячейке в первом столбце и третьей строке DataFrame из пункта c
# ------------------------------------------------------------
# Первый столбец — 'c1', третья строка — 'row3' (индекс 'row3')
# Используем .loc (по меткам) или .iloc (по позициям)
cell_value_loc = df_c.loc['row3', 'c1']   # по именам индексов
cell_value_iloc = df_c.iloc[2, 0]         # по позициям (3-я строка, 1-й столбец)
print("f) Ячейка первого столбца и третьей строки:")
print("   .loc:   ", cell_value_loc)
print("   .iloc:  ", cell_value_iloc)
print()
