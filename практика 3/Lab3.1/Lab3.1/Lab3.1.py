# Импорт необходимых библиотек
import pandas as pd
import numpy as np

# Для воспроизводимости результатов (можно убрать, если нужны разные случайные числа)
np.random.seed(42)

# ------------------------------------------------------------
# a) Создание Series из списка с самостоятельно заданными индексами
# ------------------------------------------------------------
data_list = [10, 20, 30, 40, 50]
custom_index = ['a', 'b', 'c', 'd', 'e']
series_a = pd.Series(data_list, index=custom_index)
print("a) Series из списка с кастомными индексами:")
print(series_a)
print()

# ------------------------------------------------------------
# b) Создание Series из словаря (ключи → индексы, значения → данные)
# ------------------------------------------------------------
data_dict = {'apple': 1.5, 'banana': 2.2, 'orange': 0.8, 'grape': 3.1}
series_b = pd.Series(data_dict)
print("b) Series из словаря:")
print(series_b)
print()

# ------------------------------------------------------------
# c) Создание Series из массива NumPy с двузначными целыми числами
# ------------------------------------------------------------
np_array = np.random.randint(10, 100, size=7)  # 7 случайных двузначных чисел
series_c = pd.Series(np_array)
print("c) Series из массива NumPy (двузначные числа):")
print(series_c)
print()

# ------------------------------------------------------------
# d) Получение атрибутов values и index у Series из пункта b
# ------------------------------------------------------------
print("d) Атрибуты values и index для Series из пункта b:")
print("Значения (values):", series_b.values)
print("Индексы (index):", series_b.index)
print()

# ------------------------------------------------------------
# e) Изменение последнего элемента Series из пункта c 
#    (синтаксис, аналогичный работе со словарями)
# ------------------------------------------------------------
last_index = series_c.index[-1]   # индекс последнего элемента
series_c[last_index] = 999        # новое значение
print("e) Series из пункта c после изменения последнего элемента:")
print(series_c)
print()

# ------------------------------------------------------------
# f) Срез Series из пункта c: все элементы, кроме первых двух
# ------------------------------------------------------------
slice_f = series_c.iloc[2:]       # позиционный срез (с 3-го элемента)
print("f) Срез Series из пункта c (без первых двух элементов):")
print(slice_f)
print()

# ------------------------------------------------------------
# g) Выбор элементов Series из пункта c, превышающих 35
# ------------------------------------------------------------
filtered_g = series_c[series_c > 35]
print("g) Элементы Series из пункта c, превышающие 35:")
print(filtered_g)
